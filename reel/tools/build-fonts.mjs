// Downloads the (SIL OFL) Google Fonts used by the reel and embeds their latin
// subsets as base64 in src/fonts.js, so the page renders identically offline,
// from file://, and inside the headless renderer.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const FAMILIES = [
  'Anton',
  'Barlow+Condensed:ital,wght@0,500;0,700;0,800;1,800;1,900',
  'Bangers',
];
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

const url = 'https://fonts.googleapis.com/css2?' + FAMILIES.map((f) => 'family=' + f).join('&') + '&display=block';
const css = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();

const faces = [];
for (const m of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)) {
  if (m[1] !== 'latin') continue;
  const body = m[2];
  const family = /font-family:\s*'([^']+)'/.exec(body)[1];
  const style = /font-style:\s*(\w+)/.exec(body)[1];
  const weight = /font-weight:\s*(\d+)/.exec(body)[1];
  const src = /url\(([^)]+)\)/.exec(body)[1];
  const buf = Buffer.from(await (await fetch(src)).arrayBuffer());
  faces.push({ family, style, weight, data: buf.toString('base64') });
  console.log(`${family} ${weight} ${style}: ${(buf.length / 1024).toFixed(1)} KB`);
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'fonts.js');
await writeFile(out,
  '// Generated by tools/build-fonts.mjs — Anton, Barlow Condensed, Bangers (SIL Open Font License 1.1).\n' +
  'window.REEL_FONTS = ' + JSON.stringify(faces) + ';\n');
console.log('wrote', out);
